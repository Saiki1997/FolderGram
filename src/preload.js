'use strict';

const { contextBridge, ipcRenderer, webUtils } = require('electron');

const call = async (channel, ...args) => {
  const r = await ipcRenderer.invoke(channel, ...args);
  if (!r.ok) throw new Error(r.error);
  return r.value;
};

const EVENTS = ['log', 'progress', 'upload:done', 'prompt', 'toast', 'scan:progress', 'queue:changed', 'wait', 'album', 'download:progress', 'sync:changed'];

contextBridge.exposeInMainWorld('fg', {
  getSettings: () => call('settings:get'),
  setSettings: (patch) => call('settings:set', patch),
  login: (creds) => call('auth:login', creds),
  accounts: () => call('accounts:list'),
  profiles: () => call('profiles:list'),
  stats: () => call('stats:summary'),
  createBackup: (o) => call('backup:create', o),
  autoBackups: () => call('backup:list'),
  inspectBackup: (auto, password) => call('backup:inspect', auto, password),
  restoreBackup: (password) => call('backup:restore', password),
  saveProfile: (p) => call('profiles:save', p),
  removeProfile: (id) => call('profiles:remove', id),
  addAccount: (name, copy) => call('accounts:add', name, copy),
  renameAccount: (id, name) => call('accounts:rename', id, name),
  removeAccount: (id) => call('accounts:remove', id),
  switchAccount: (id) => call('accounts:switch', id),
  logout: (asBot) => call('auth:logout', asBot),
  listGroups: () => call('groups:list'),
  resolveGroup: (text) => call('groups:resolve', text),
  listTopics: (chat) => call('topics:list', chat),
  createTopic: (chat, title) => call('topics:create', chat, title),
  pickFolders: () => call('folder:pick'),
  pickFiles: () => call('files:pick'),
  scan: (sources, opts, force) => call('sources:scan', sources, opts, force),
  thumbs: (ids) => call('thumbs:get', ids),
  savePlan: (edits, opts, sources) => call('plan:save', edits, opts, sources),
  loadPlan: () => call('plan:load'),
  naming: () => call('naming:get'),
  correctAlbum: (c) => call('naming:correctAlbum', c),
  correctTopic: (from, to) => call('naming:correctTopic', from, to),
  setRules: (rules) => call('naming:setRules', rules),
  forgetNaming: (kind, from) => call('naming:forget', kind, from),
  setDictionary: (list) => call('naming:setDictionary', list),
  setOrganize: (list) => call('naming:setOrganize', list),
  organizePresets: () => call('organize:presets'),
  tryNaming: (text, opts, rules) => call('naming:try', text, opts, rules),
  findSimilar: (ids, opts) => call('similar:find', ids, opts),
  suggestCovers: (sets) => call('covers:suggest', sets),
  cancelAnalysis: () => call('analysis:cancel'),
  libraryTopics: (chat) => call('library:topics', chat),
  libraryPage: (chat, topicId, reset) => call('library:page', chat, topicId, reset),
  libraryThumbs: (chat, ids) => call('library:thumbs', chat, ids),
  libraryOpen: (chat, id, topicId) => call('library:open', chat, id, topicId),
  libraryCompare: (chat, topicId, sets) => call('library:compare', chat, topicId, sets),
  libraryChecks: (chat) => call('library:checks', chat),
  renameTopic: (chat, topicId, title) => call('library:renameTopic', chat, topicId, title),
  editCaption: (chat, id, text) => call('library:editCaption', chat, id, text),
  resendMissing: (chat, album) => call('library:resendMissing', chat, album),
  pickDownloadFolder: () => call('downloads:pickFolder'),
  startDownload: (spec) => call('downloads:start', spec),
  cancelDownload: () => call('downloads:cancel'),
  listDownloads: () => call('downloads:list'),
  openDownloadFolder: (dest) => call('downloads:openFolder', dest),
  syncList: () => call('sync:list'),
  syncSave: (p) => call('sync:save', p),
  syncRemove: (id) => call('sync:remove', id),
  syncRun: (id) => call('sync:run', id),
  syncDeleteRemoved: (id, paths) => call('sync:deleteRemoved', id, paths),
  syncDownloadNew: (id, keys) => call('sync:downloadNew', id, keys),
  checkDuplicates: (spec) => call('duplicates:check', spec),
  queueAdd: (spec) => call('queue:add', spec),
  queueList: () => call('queue:list'),
  queuePause: (id) => call('queue:pause', id),
  queueResume: (id) => call('queue:resume', id),
  queueCancel: (id) => call('queue:cancel', id),
  queueRetry: (id) => call('queue:retry', id),
  queueRemove: (id) => call('queue:remove', id),
  queueMove: (id, to) => call('queue:move', id, to),
  queueSchedule: (id, at) => call('queue:schedule', id, at),
  queueClearFinished: () => call('queue:clearFinished'),
  queueReview: (id, action) => call('queue:review', id, action),
  report: (id) => call('queue:report', id),
  exportReport: (id, format) => call('report:export', id, format),
  checkUpdate: () => call('update:check'),
  cancelUpload: () => call('upload:cancel'),
  pauseUpload: (paused) => call('upload:pause', paused),
  pathForFile: (file) => webUtils.getPathForFile(file),
  clearHistory: () => call('history:clear'),
  openData: () => call('data:open'),
  openLogs: () => call('logs:open'),
  saveLog: () => call('logs:save'),
  backups: () => call('data:backups'),
  openExternal: (url) => call('open:external', url),
  on: (channel, fn) => {
    if (!EVENTS.includes(channel)) return;
    ipcRenderer.on(channel, (_e, payload) => fn(payload));
  },
  replyPrompt: (id, value) => ipcRenderer.send('prompt:reply', { id, value }),
});
